namespace ModTwoAuth\Providers;

use MODX\Revolution\modX;

class TotpProvider extends BaseProvider
{
    public function generateSecret(int $length = 32): string
    {
        $chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';
        $secret = '';
        for ($i = 0; $i < $length; $i++) {
            $secret .= $chars[random_int(0, 31)];
        }
        return $secret;
    }

    public function getQrUrl(string $secret, string $label, string $issuer = 'MODX'): array
    {
        $label = trim($label) !== '' ? $label : 'MODX User';
        $issuer = trim($issuer) !== '' ? $issuer : 'MODX';

        $otpauth = 'otpauth://totp/' . rawurlencode($issuer . ':' . $label)
            . '?secret=' . rawurlencode($secret)
            . '&issuer=' . rawurlencode($issuer)
            . '&algorithm=SHA1&digits=6&period=30';

        // Return the payload only. The bundled local browser encoder renders the QR.

        return [
            'qr_data' => $otpauth,
            'otpauth' => $otpauth,
            'secret' => $secret,
        ];
    }

    public function sendCode(int $userId, string $contact, string $code): bool
    {
        // TOTP codes are generated by the authenticator app.
        return false;
    }

    /**
     * Проверяет 6-значный TOTP-код (RFC 6238) с окном ±1 и защитой от повторного
     * использования кода (replay): шаги времени <= $lastUsedStep отклоняются.
     *
     * @param string   $secret       Base32-секрет
     * @param string   $code         Проверяемый код
     * @param int      $lastUsedStep Последний принятый timestep (0 = ограничения нет)
     * @param int|null $matchedStep  Возвращается timestep совпавшего кода (для записи в БД)
     */
    public function verifyCode(string $secret, string $code, int $lastUsedStep = 0, ?int &$matchedStep = null): bool
    {
        $matchedStep = null;
        if ($secret === '' || !preg_match('/^\d{6}$/', $code)) {
            return false;
        }

        $timeSlice = (int) floor(time() / 30);

        for ($i = -1; $i <= 1; $i++) {
            $step = $timeSlice + $i;
            // RFC 6238 §5.2: код уже принятого шага времени не должен приниматься повторно.
            if ($step <= $lastUsedStep) {
                continue;
            }
            $calculatedCode = $this->getCode($secret, $step);
            if (hash_equals($calculatedCode, $code)) {
                $matchedStep = $step;
                return true;
            }
        }

        return false;
    }

    private function getCode(string $secret, int $timeSlice): string
    {
        $secretKey = self::base32Decode($secret);
        if ($secretKey === '') {
            return '';
        }

        $time = pack('N*', 0) . pack('N*', $timeSlice);
        $hash = hash_hmac('sha1', $time, $secretKey, true);
        $offset = ord(substr($hash, -1)) & 0x0F;
        $part = substr($hash, $offset, 4);
        $value = unpack('N', $part)[1] & 0x7FFFFFFF;

        return str_pad((string) ($value % 1000000), 6, '0', STR_PAD_LEFT);
    }

    private static function base32Decode(string $input): string
    {
        $map = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';
        $input = strtoupper(str_replace('=', '', trim($input)));
        $buffer = 0;
        $bufferSize = 0;
        $output = '';

        for ($i = 0, $len = strlen($input); $i < $len; $i++) {
            $value = strpos($map, $input[$i]);
            if ($value === false) {
                return '';
            }

            $buffer = ($buffer << 5) | $value;
            $bufferSize += 5;

            if ($bufferSize >= 8) {
                $bufferSize -= 8;
                $output .= chr(($buffer >> $bufferSize) & 0xFF);
            }
        }

        return $output;
    }
}
